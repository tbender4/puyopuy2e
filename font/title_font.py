def glyph(ch):
    """16 rows of 8 pixels (0/1), the letter on rows 1-13"""
    rows = [[0] * 8 for _ in range(16)]
    if ch == ' ':
        return rows
    art = ART[ch].strip('\n').split('\n')
    for y, line in enumerate(art):
        for x, c in enumerate(line):
            rows[1 + y][x] = 1 if c == '#' else 0
    return rows

